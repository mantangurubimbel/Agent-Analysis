-- Jalankan melalui Supabase SQL Editor.
-- Snapshot invoice menjaga nilai billing tetap stabil setelah diterbitkan.
create table if not exists public.invoice_settings (
  id integer primary key default 1 check (id = 1),
  global_rate numeric(12,2) not null default 0,
  due_days integer not null default 14 check (due_days between 1 and 90),
  grace_days integer not null default 0 check (grace_days between 0 and 90),
  currency text not null default 'IDR',
  company_name text,
  company_address text,
  payment_instructions text,
  updated_at timestamp without time zone not null default now(),
  updated_by bigint
);

create table if not exists public.invoice_supervisor_rates (
  supervisor_id bigint primary key references public.users(id) on delete cascade,
  rate numeric(12,2) not null check (rate >= 0),
  updated_at timestamp without time zone not null default now(),
  updated_by bigint
);

create table if not exists public.invoices (
  id bigint generated by default as identity primary key,
  invoice_number text not null unique,
  supervisor_id bigint not null references public.users(id),
  period_month date not null,
  issued_at timestamp without time zone not null default now(),
  due_at timestamp without time zone not null,
  status text not null default 'issued' check (status in ('draft','issued','paid','overdue','suspended','cancelled')),
  total_chats integer not null default 0,
  rate numeric(12,2) not null default 0,
  subtotal numeric(12,2) not null default 0,
  total numeric(12,2) not null default 0,
  paid_at timestamp without time zone,
  paid_by bigint,
  notes text,
  created_at timestamp without time zone not null default now(),
  unique (supervisor_id, period_month)
);

create table if not exists public.invoice_items (
  id bigint generated by default as identity primary key,
  invoice_id bigint not null references public.invoices(id) on delete cascade,
  uploader_id bigint references public.users(id),
  uploader_name_snapshot text not null,
  uploader_role text not null,
  chat_count integer not null default 0,
  rate numeric(12,2) not null default 0,
  amount numeric(12,2) not null default 0
);

create index if not exists invoices_period_idx on public.invoices(period_month);
create index if not exists invoices_status_idx on public.invoices(status);
alter table public.invoice_settings disable row level security;
alter table public.invoice_supervisor_rates disable row level security;
alter table public.invoices disable row level security;
alter table public.invoice_items disable row level security;
